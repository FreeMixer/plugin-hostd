# src/reply_words.h: the error word of every refusal number plugin-hostd-protocol declares a code for (its reply_codes),
# which the daemon writes after the number in a session granted the extension errors. Written from the protocol's JSON
# at build time, never by hand and never committed.
#
#   tools/reply-words.py <plugin-hostd-protocol.json>   prints src/reply_words.h
import json
import re
import sys


def fail(msg):
    sys.exit(f"reply-words: {msg}")


def header(table):
    TABLE = table
    try:
        with open(table, encoding="utf-8") as f:
            codes = json.load(f)["reply_codes"]
    except (OSError, ValueError, KeyError) as e:
        fail(f"{TABLE}: {e}")
    if not codes:
        fail(f"{TABLE}: no reply code")
    o = ["/* GENERATED by tools/reply-words.py from the protocol JSON (reply_codes): do not edit. */",
         "#ifndef REPLY_WORDS_H", "#define REPLY_WORDS_H", "",
         "/* the error word of each refusal number the protocol declares a code for (the extension errors) */",
         "static const struct reply_word { int resp; const char *code; } g_reply_words[] = {"]
    for c in codes:
        if not isinstance(c["resp"], int) or c["resp"] >= 0 or not re.fullmatch(r"[a-z0-9.-]+", c["code"]):
            fail(f"{TABLE}: {c} is no refusal number and code")
        o.append(f'    {{ {c["resp"]}, "{c["code"]}" }},')
    o += ["};", "", "#endif"]
    return "\n".join(o) + "\n"


def main():
    if len(sys.argv) != 2:
        fail(f"usage: {sys.argv[0]} <plugin-hostd-protocol.json>")
    sys.stdout.write(header(sys.argv[1]))


if __name__ == "__main__":
    main()
